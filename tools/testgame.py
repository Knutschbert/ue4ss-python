#!/usr/bin/env python3
"""Run the in-game test scripts (python/examples) in the test game, unattended (Windows).

    python tools\\testgame.py install                    # UE4SS, its settings and the mod into the staged PyTestGame
    python tools\\testgame.py run arrays_main            # one script; prints its PASS / FAIL counts
    python tools\\testgame.py all                        # every test of python/examples/manifest.json; exit code 0 only if all pass
    python tools\\testgame.py all --only arrays_main,enums_main

Before: stage the game (tools\\package_testgame.ps1) and build UE4SS, the proxy and the mod (tools\\build.ps1, or
`python tools\\install.py` once for any game). `install` packages the mod itself.

How one script is run: it is written as the mod's main.py, the game is started headless, UE4SS.log is read until the script's
finish marker appears (or a timeout, a crash dump, or the game exiting), and exactly the process that was started is ended.
One game process per script, one after another: scripts leave hooks and subscriptions behind. The main.py that was there
before is put back. What each script printed is in testgame/runs/<name>.txt, the verdicts in testgame/last_results.json.
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, List, Optional

sys.path.insert(0, str(Path(__file__).resolve().parent))
import install as installer  # noqa: E402
import package_mod  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
MOD_NAME = "PythonScripting"
EXE_NAME = "PyTestGame-Win64-Shipping.exe"
GAME_DIR = ROOT / "testgame" / "PyTestGame" / "Saved" / "StagedBuilds" / "WindowsNoEditor" / "PyTestGame" / "Binaries" / "Win64"
SETTINGS_DIR = ROOT / "testgame" / "ue4ss"
EXAMPLES = ROOT / "python" / "examples"
MANIFEST = EXAMPLES / "manifest.json"
RUNS = ROOT / "testgame" / "runs"
RESULTS = ROOT / "testgame" / "last_results.json"
TARGET = "testgame"
HEADLESS_ARGS = ["-nullrhi", "-nosound", "-nosplash", "-unattended"]
POLL_SECONDS = 0.5
TEST_COPY_MARK = "# test copy: written by tools/testgame.py for a test run"

_PASS = re.compile(r"^PASS\b|: PASS\b")
_FAIL = re.compile(r"^FAIL\b|: FAIL\b|^Traceback")
_PLAIN_FAIL = re.compile(r"^FAIL\b|: FAIL\b")
_SKIP = re.compile(r"^SKIP\b|: SKIP\b")

# Under load the mod's main.py can run on the first engine tick, before the test game's game mode has spawned its actors. A
# script is therefore started by this wrapper once the three test actors exist (without blocking the game thread). Scripts
# that depend on being main.py itself say "startup": true in the manifest and are copied as they are.
WORLD_WRAPPER = '''# generated by tools/testgame.py: start __NAME__ once the test world is up
import time

import ue4ss

_NAME = __NAME_REPR__
_SOURCE = __SOURCE_REPR__
_DEADLINE = time.monotonic() + 40


def _poll():
    try:
        ready = len(ue4ss.find_all_of("PyTestActor")) >= 3
    except Exception:
        ready = False
    if not ready and time.monotonic() < _DEADLINE:
        ue4ss.execute_with_delay(50, _poll)
        return
    exec(compile(_SOURCE, _NAME, "exec"), {"__name__": "__main__", "__file__": _NAME})


ue4ss.execute_with_delay(0, _poll)
'''


class TestGameError(Exception):
    pass


# --- the manifest ------------------------------------------------------------------------------------------------------
def load_manifest(path: Path = MANIFEST) -> list:
    return json.loads(path.read_text(encoding="utf-8"))["examples"]


def selected(entries: list, only: Optional[list] = None) -> list:
    """The test scripts of the test game, in manifest order; `only` narrows by file name (with or without .py)."""
    tests = [e for e in entries if e.get("kind") == "test" and TARGET in e.get("targets", [])]
    if not only:
        return tests
    wanted = {name if name.endswith(".py") else name + ".py" for name in only}
    unknown = wanted - {e["file"] for e in entries}
    if unknown:
        raise TestGameError("not in the manifest: " + ", ".join(sorted(unknown)))
    return [e for e in entries if e["file"] in wanted]


def min_pass_for(entry: dict) -> int:
    floor = entry.get("min_pass", 0)
    return int(floor.get(TARGET, 0)) if isinstance(floor, dict) else int(floor)


# --- reading the log -----------------------------------------------------------------------------------------------------
def python_lines(log_text: str) -> list:
    """The [Python] output lines, without the log's timestamp prefix."""
    return [raw.split("[Python] ", 1)[1] if "[Python] " in raw else "" for raw in log_text.splitlines() if "[Python]" in raw]


def summarize(lines: list, marker: str) -> dict:
    """PASS / FAIL / SKIP counts. "PASS name" and "name: PASS (detail)" both count; a traceback counts as a failure. The summary
    line a script prints at the end ("... PASS=3 FAIL=0") is not counted."""
    return {"pass": sum(1 for line in lines if _PASS.search(line)), "fail": sum(1 for line in lines if _FAIL.search(line)),
            "skip": sum(1 for line in lines if _SKIP.search(line)), "finished": any(marker in line for line in lines)}


@dataclass
class RunResult:
    example: str
    started: bool = False
    finished: bool = False
    passed: int = 0
    failed: int = 0
    skipped: int = 0
    seconds: float = 0.0
    exit_seconds: Optional[float] = None    # with expect_exit_within: how long the game needed to exit after the marker
    problem: str = ""                       # why the run could not give a verdict ("" when it did)
    lines: List[str] = field(default_factory=list)


def verdict(entry: dict, result: RunResult) -> str:
    """'' when the script passed, otherwise why not."""
    if result.problem:
        return result.problem
    if not result.finished:
        return "did not print its finish marker"
    failed = sum(1 for line in result.lines if _PLAIN_FAIL.search(line)) if entry.get("tolerate_tracebacks") else result.failed
    if failed:
        return f"{failed} FAIL/traceback line(s)"
    if result.passed < min_pass_for(entry):
        return f"only {result.passed} PASS lines, expected at least {min_pass_for(entry)}"
    return ""


def main_py_for(entry: dict, example: Path) -> str:
    source = example.read_text(encoding="utf-8")
    if entry.get("startup"):
        return TEST_COPY_MARK + "\n" + source
    wrapper = WORLD_WRAPPER.replace("__NAME_REPR__", repr(example.name)).replace("__SOURCE_REPR__", repr(source)).replace("__NAME__", example.name)
    return TEST_COPY_MARK + "\n" + wrapper


# --- the game process ----------------------------------------------------------------------------------------------------
class Game:
    """Starts and ends the game. Tests replace it with a fake."""

    def __init__(self, game_dir: Path = GAME_DIR, exe_name: str = EXE_NAME):
        self.game_dir, self.exe_name = Path(game_dir), exe_name
        self.process = None

    @property
    def log(self) -> Path:
        return self.game_dir / "UE4SS.log"

    def start(self, args: list, env: Optional[dict] = None) -> None:
        environment = dict(os.environ)
        environment.update(env or {})
        self.process = subprocess.Popen([str(self.game_dir / self.exe_name)] + list(args), cwd=str(self.game_dir), env=environment,
                                        stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    def alive(self) -> bool:
        return self.process is not None and self.process.poll() is None

    def stop(self) -> str:
        if self.process is None:
            return "not started"
        if self.process.poll() is not None:
            return f"had exited (code {self.process.returncode})"
        self.process.terminate()                    # only the process this runner started
        try:
            self.process.wait(timeout=20)
        except subprocess.TimeoutExpired:
            self.process.kill()
            self.process.wait(timeout=20)
        return "ended"

    def crash_dumps(self) -> set:
        return {dump.name for dump in self.game_dir.glob("crash_*.dmp")}


def run_example(entry: dict, *, game: Optional[Game] = None, root: Path = ROOT, examples: Path = EXAMPLES, timeout: float = 150, extra_seconds: float = 1.0,
                windowed: bool = False, clock: Callable[[], float] = time.monotonic, sleep: Callable[[float], None] = time.sleep, echo: Callable[[str], None] = print) -> RunResult:
    """Deploy the script as the mod's main.py, start the game, wait for its marker, end the process."""
    game = game or Game()
    result = RunResult(example=entry["file"])
    example = examples / entry["file"]
    main_py = root / "dist" / MOD_NAME / "python_scripts" / "main.py"
    if not (game.game_dir / game.exe_name).exists():
        result.problem = f"{game.exe_name} is not staged in {game.game_dir}: run tools\\package_testgame.ps1"
        return result
    if not (game.game_dir / "UE4SS.dll").exists() or not main_py.parent.exists():
        result.problem = "UE4SS or the mod is not installed in the test game: run  python tools\\testgame.py install"
        return result
    # The shared main.py can be the developer's own script: put it back afterwards. A file this runner wrote is not worth keeping.
    previous = main_py.read_bytes() if main_py.exists() else None
    if previous is not None and previous.startswith(TEST_COPY_MARK.encode()):
        previous = None
    main_py.write_text(main_py_for(entry, example), encoding="utf-8")
    if game.log.exists():
        game.log.unlink()                           # so that only this run's output is read
    known_dumps = game.crash_dumps()
    marker, tolerate = entry["marker"], bool(entry.get("tolerate_tracebacks"))
    pattern = re.compile(re.escape(marker) + ("" if tolerate else "|Traceback"))
    began = clock()
    try:
        game.start([] if windowed else HEADLESS_ARGS, entry.get("env"))
        result.started = True
        polls = 0
        while True:
            if clock() - began >= timeout:
                result.problem = f"timed out after {timeout:.0f} s without the marker"
                break
            sleep(POLL_SECONDS)
            polls += 1
            if pattern.search("\n".join(_read_lines(game.log))):
                result.seconds = clock() - began
                break
            if polls % 4 == 0:
                if game.crash_dumps() - known_dumps:
                    result.problem = "the game crashed (a crash dump was written)"
                    break
                if not game.alive():
                    if pattern.search("\n".join(_read_lines(game.log))):     # it printed the marker and quit between two looks
                        result.seconds = clock() - began
                    else:
                        result.problem = "the game exited on its own before the marker"
                    break
        expect_exit = entry.get("expect_exit_within")
        if expect_exit is not None and not result.problem:
            waited = clock()                        # the script makes the game quit: a hang at exit shows up here
            while game.alive():
                if clock() - waited >= expect_exit:
                    result.problem = f"the game was still running {expect_exit} s after the marker (hang at exit)"
                    break
                sleep(POLL_SECONDS)
            else:
                result.exit_seconds = clock() - waited
        elif not result.problem:
            sleep(extra_seconds)                    # lines printed right after the marker
    finally:
        echo(f"  game: {game.stop()}")
        if previous is not None:
            main_py.write_bytes(previous)
    result.lines = _read_lines(game.log)
    summary = summarize(result.lines, marker)
    result.passed, result.failed, result.skipped, result.finished = summary["pass"], summary["fail"], summary["skip"], summary["finished"]
    return result


def _read_lines(log: Path) -> list:
    try:
        return python_lines(log.read_text(encoding="utf-8", errors="replace"))
    except OSError:
        return []                                   # not written yet, or the game holds it for a moment


# --- commands --------------------------------------------------------------------------------------------------------------
def install(*, build: bool = False, say: Callable[[str], None] = print) -> None:
    """UE4SS, the test game's own UE4SS settings and the mod into the staged test game."""
    if not (GAME_DIR / EXE_NAME).exists():
        raise TestGameError(f"{EXE_NAME} is not staged in {GAME_DIR}: run tools\\package_testgame.ps1 first")
    steps = installer.Installer(say=say)
    steps.check_not_running(EXE_NAME)
    if build:
        steps.build_all()
    steps.package_mod()
    # the test game's settings belong to this repository (UE4SS windows off): always the repository's copy
    shutil.copy2(SETTINGS_DIR / "UE4SS-settings.ini", GAME_DIR / "UE4SS-settings.ini")
    (GAME_DIR / "Mods").mkdir(exist_ok=True)
    shutil.copy2(SETTINGS_DIR / "Mods" / "mods.txt", GAME_DIR / "Mods" / "mods.txt")
    steps.install_ue4ss(GAME_DIR)
    steps.install_mod(GAME_DIR, copy=False)
    say(f"the test game is ready: {GAME_DIR}")


def run_all(entries: list, *, timeout: float = 150, windowed: bool = False, runner: Callable = run_example, say: Callable[[str], None] = print,
            runs: Path = RUNS, results: Path = RESULTS, root: Path = ROOT, examples: Path = EXAMPLES) -> int:
    """Run the scripts one after another; write per-script output and the result file. Returns the number that did not pass."""
    runs.mkdir(parents=True, exist_ok=True)
    report, failures, expected = [], 0, 0
    for number, entry in enumerate(entries, 1):
        say(f"[{number}/{len(entries)}] {entry['file']}")
        result = runner(entry, root=root, examples=examples, timeout=timeout, windowed=windowed, echo=say)
        why = verdict(entry, result)
        (runs / (Path(entry["file"]).stem + ".txt")).write_text("\n".join(result.lines) + "\n", encoding="utf-8")
        known = entry.get("expected_failure", "")          # a known defect: failing is expected, passing means the entry is out of date
        if known and why:
            state, ok = "KNOWN", True
            expected += 1
        elif known:
            state, ok, why = "FAIL", False, "passed although the manifest says expected_failure: remove that entry"
        else:
            state, ok = ("ok  " if not why else "FAIL"), not why
        say(f"  {state} PASS={result.passed} FAIL={result.failed} SKIP={result.skipped} in {result.seconds:.1f} s" + (f"  -- {why}" if why else "")
            + (f"  (known: {known})" if state == "KNOWN" else ""))
        for line in [l for l in result.lines if _FAIL.search(l)][:6] if why and state == "FAIL" else []:
            say("      " + line[:200])
        failures += not ok
        report.append({"file": entry["file"], "ok": ok, "why": why, "expected_failure": state == "KNOWN", "pass": result.passed, "fail": result.failed,
                       "skip": result.skipped, "seconds": round(result.seconds, 1), "started": result.started})
    results.write_text(json.dumps({"target": TARGET, "total": len(entries), "failed": failures, "expected_failures": expected, "examples": report}, indent=1) + "\n",
                       encoding="utf-8")
    say(f"{len(entries) - failures - expected} of {len(entries)} passed" + (f", {expected} failed as expected (known defects)" if expected else "")
        + (f", {failures} did not: " + ", ".join(r["file"] for r in report if not r["ok"]) if failures else ""))
    return failures


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--examples-dir", type=Path, default=EXAMPLES, help="the folder holding example scripts (default: %(default)s)")
    parser.add_argument("--manifest", type=Path, help="the example manifest (default: <examples-dir>/manifest.json)")
    sub = parser.add_subparsers(dest="command", required=True)
    install_parser = sub.add_parser("install", help="UE4SS, its settings and the mod into the staged test game")
    install_parser.add_argument("--build", action="store_true", help="build UE4SS, the proxy and the mod first")
    for name, text in (("run", "run one script"), ("all", "run every test script of the manifest")):
        command = sub.add_parser(name, help=text)
        if name == "run":
            command.add_argument("example", help="file name in python/examples, with or without .py")
        else:
            command.add_argument("--only", default="", help="comma separated file names")
        command.add_argument("--timeout", type=float, default=150, help="seconds to wait for a script's marker (default: %(default)s)")
        command.add_argument("--windowed", action="store_true", help="show the game window (default: headless)")
    args = parser.parse_args(argv)
    try:
        if os.name != "nt":
            raise TestGameError("run this with a Windows Python: it starts and ends the game process")
        if args.command == "install":
            install(build=args.build)
            return 0
        if package_mod.running_game([EXE_NAME]):
            raise TestGameError(f"{EXE_NAME} is already running; close it first")
        examples = args.examples_dir
        entries = load_manifest(args.manifest or examples / "manifest.json")
        chosen = selected(entries, [args.example] if args.command == "run" else [n for n in args.only.split(",") if n])
        if not chosen:
            raise TestGameError("no script selected")
        return 1 if run_all(chosen, timeout=args.timeout, windowed=args.windowed, examples=examples) else 0
    except (TestGameError, installer.InstallError) as error:
        print("testgame: " + str(error), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
