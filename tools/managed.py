#!/usr/bin/env python3
"""Install and configure the opt-in managed-runtime bootstrap."""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MOD = ROOT / "dist" / "PythonScripting"
SCRIPTS = "python_scripts"
STATE_DIR = "managed_runtime"
MANIFEST = "manifest.json"
BOOTSTRAP_MARK = "# generated by tools.managed_runtime"
LIVE_MARK = "# generated by tools.live_bridge"
BACKUP_NAME = "main.py.before-managed"
LIVE_NAME = "LiveBridge"
LIVE_SOURCE = ROOT / "tools" / "managed_components" / LIVE_NAME

sys.path.insert(0, str(ROOT / "python" / "lib"))
from ue4ss.runtime.bootstrap import empty_manifest, load_manifest  # noqa: E402


class ManagedInstallError(RuntimeError):
    """A managed install/configuration change cannot be made safely."""


def _manifest_path(mod: Path) -> Path:
    return mod / STATE_DIR / MANIFEST


def _read_manifest(mod: Path) -> dict:
    if (mod / STATE_DIR).is_symlink():
        raise ManagedInstallError(f"{mod / STATE_DIR} may not be a symlink")
    path = _manifest_path(mod)
    return load_manifest(path)


def _write_manifest(path: Path, manifest: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".new")
    if temporary.exists():
        raise ManagedInstallError(f"refusing to overwrite stale temporary manifest: {temporary}")
    try:
        payload = (json.dumps(manifest, ensure_ascii=False, indent=2, allow_nan=False) + "\n").encode("utf-8")
        with temporary.open("xb") as stream:
            stream.write(payload)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    except BaseException:
        try:
            temporary.unlink()
        except OSError:
            pass
        raise


def _bootstrap_source() -> str:
    return (
        f"{BOOTSTRAP_MARK}\n"
        '"""Stable entry point; managed component configuration lives beside this file."""\n'
        "from ue4ss.runtime.bootstrap import start\n"
        "start(__file__)\n"
    )


def install(mod: Path = MOD, say=print, *, dry_run: bool = False) -> None:
    scripts = mod / SCRIPTS
    if not scripts.is_dir():
        raise ManagedInstallError(f"{scripts} does not exist: package the mod first")
    main = scripts / "main.py"
    backup = scripts / BACKUP_NAME
    state_dir = mod / STATE_DIR
    manifest_path = _manifest_path(mod)

    if state_dir.is_symlink():
        raise ManagedInstallError(f"{state_dir} may not be a symlink")
    if manifest_path.is_symlink():
        raise ManagedInstallError(f"{manifest_path} may not be a symlink")
    if main.is_symlink() or backup.is_symlink():
        raise ManagedInstallError("main.py and its managed backup may not be symlinks")
    if main.is_file() and main.read_text(encoding="utf-8", errors="replace").startswith(BOOTSTRAP_MARK):
        _read_manifest(mod)
        say("managed bootstrap is already installed")
        return
    if backup.exists():
        raise ManagedInstallError(f"{backup} already exists; refusing ambiguous main.py migration")
    if main.exists():
        text = main.read_text(encoding="utf-8", errors="replace")
        is_live_bridge = text.startswith(LIVE_MARK)
        live_backup = scripts / "main.py.before-live"
        if live_backup.is_symlink():
            raise ManagedInstallError(f"{live_backup} may not be a symlink")
        if live_backup.exists() and not is_live_bridge:
            raise ManagedInstallError(
                f"{live_backup} exists but main.py is not the generated live bridge; resolve the backup state by hand"
            )
        if main.is_dir():
            raise ManagedInstallError(f"{main} is not a file")
    elif backup.exists():
        raise ManagedInstallError(f"{backup} exists without main.py; resolve the backup state by hand")

    manifest_exists = manifest_path.exists()
    if manifest_exists:
        _read_manifest(mod)

    temporary = scripts / ".main.py.managed-new"
    if temporary.exists():
        raise ManagedInstallError(f"refusing to overwrite stale bootstrap file: {temporary}")
    if dry_run:
        say(f"would install managed bootstrap as {main}")
        if main.exists():
            say(f"would preserve current main.py as {backup.name}")
        if not manifest_exists:
            say(f"would initialize an empty manifest at {manifest_path}")
        return
    if not manifest_exists:
        state_dir.mkdir(parents=True, exist_ok=True)
        _write_manifest(manifest_path, empty_manifest())
    moved_main = False
    try:
        if main.exists():
            main.replace(backup)
            moved_main = True
            say(f"previous main.py preserved as {backup.name}")
        temporary.write_text(_bootstrap_source(), encoding="utf-8")
        temporary.replace(main)
    except BaseException:
        try:
            temporary.unlink()
        except OSError:
            pass
        if moved_main and backup.exists() and not main.exists():
            backup.replace(main)
        raise
    say(f"managed bootstrap installed as {main}; no components are enabled by default")


def uninstall(mod: Path = MOD, say=print, *, dry_run: bool = False) -> None:
    main = mod / SCRIPTS / "main.py"
    backup = mod / SCRIPTS / BACKUP_NAME
    if main.is_symlink() or backup.is_symlink():
        raise ManagedInstallError("main.py and its managed backup may not be symlinks")
    if not main.is_file() or not main.read_text(encoding="utf-8", errors="replace").startswith(BOOTSTRAP_MARK):
        raise ManagedInstallError("main.py is not the managed bootstrap; nothing changed")
    if dry_run:
        action = f"restore {backup} to {main}" if backup.exists() else f"remove {main}"
        say(f"would {action}; managed sources/configuration remain in {STATE_DIR}/")
        return
    if backup.exists():
        backup.replace(main)
        say("previous main.py restored")
    else:
        main.unlink()
        say("managed bootstrap removed (there was no previous main.py)")
    say(f"managed sources and configuration remain in {STATE_DIR}/")


def _name(value: str) -> str:
    import re

    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_-]{0,63}", value):
        raise ManagedInstallError("component name must match [A-Za-z][A-Za-z0-9_-]{0,63}")
    return value


def _copy_package(source: Path, target: Path, *, replace: bool) -> None:
    source = Path(source)
    if source.is_symlink():
        raise ManagedInstallError("component source package may not be a symlink")
    if not source.is_dir() or not (source / "__init__.py").is_file():
        raise ManagedInstallError(f"component source must be a package directory with __init__.py: {source}")
    if any(path.is_symlink() for path in source.rglob("*")):
        raise ManagedInstallError("component source packages may not contain symlinks")
    source = source.resolve()
    if target.is_symlink():
        raise ManagedInstallError(f"managed component target may not be a symlink: {target}")
    if target.exists() and not replace:
        raise ManagedInstallError(f"{target} already exists; pass --replace to replace this managed source")
    temporary = target.with_name(target.name + ".new")
    if temporary.exists():
        raise ManagedInstallError(f"refusing to overwrite stale component staging path: {temporary}")
    try:
        shutil.copytree(source, temporary, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        if target.exists():
            retired = target.with_name(target.name + ".old")
            if retired.exists():
                raise ManagedInstallError(f"refusing to overwrite stale component backup: {retired}")
            target.replace(retired)
            try:
                temporary.replace(target)
            except BaseException:
                retired.replace(target)
                raise
            shutil.rmtree(retired)
        else:
            temporary.replace(target)
    except BaseException:
        if temporary.exists():
            shutil.rmtree(temporary, ignore_errors=True)
        raise


def enable(
    mod: Path,
    name: str,
    source: Path | None = None,
    *,
    replace: bool = False,
    dry_run: bool = False,
) -> None:
    name = _name(name)
    manifest = _read_manifest(mod)
    components = manifest["components"]
    target = mod / STATE_DIR / "components" / name
    if name not in components and source is None:
        raise ManagedInstallError("a new component requires --source with a package directory")
    if source is not None:
        if dry_run:
            source = Path(source)
            if source.is_symlink() or not source.is_dir() or not (source / "__init__.py").is_file():
                raise ManagedInstallError(f"component source must be a package directory with __init__.py: {source}")
            if any(path.is_symlink() for path in source.rglob("*")):
                raise ManagedInstallError("component source packages may not contain symlinks")
            if target.exists() and not replace:
                raise ManagedInstallError(f"{target} already exists; pass --replace to replace this managed source")
        else:
            _copy_package(source, target, replace=replace)
    elif not target.is_dir():
        raise ManagedInstallError(f"managed component source is missing: {target}")
    config = components.get(name, {"path": f"components/{name}", "config": {}})
    config["enabled"] = True
    config.setdefault("config", {})
    components[name] = config
    if name not in manifest["startup_order"]:
        manifest["startup_order"].append(name)
    if dry_run:
        print(f"would enable {name} at startup")
        return
    _write_manifest(_manifest_path(mod), manifest)


def disable(mod: Path, name: str, *, dry_run: bool = False) -> None:
    name = _name(name)
    manifest = _read_manifest(mod)
    if name not in manifest["components"]:
        raise ManagedInstallError(f"unknown managed component: {name}")
    if dry_run:
        print(f"would disable {name}")
        return
    manifest["components"][name]["enabled"] = False
    _write_manifest(_manifest_path(mod), manifest)


def configure_live(
    mod: Path,
    *,
    transport: str,
    file_config: dict | None = None,
    socket_config: dict | None = None,
    enabled: bool = True,
    dry_run: bool = False,
    token_to_validate: str | Path | None = None,
) -> None:
    if transport not in ("file", "socket", "both"):
        raise ManagedInstallError("live transport must be file, socket or both")
    if transport in ("file", "both") and not isinstance(file_config, dict):
        raise ManagedInstallError("file and both transports require file settings")
    if transport in ("file", "both"):
        if not all(
            isinstance(file_config.get(key), str) and file_config[key]
            for key in ("inbox", "outbox", "heartbeat")
        ):
            raise ManagedInstallError("file transport requires non-empty inbox, outbox and heartbeat paths")
        poll_ms = file_config.get("poll_ms", 250)
        if isinstance(poll_ms, bool) or not isinstance(poll_ms, int) or not 50 <= poll_ms <= 2000:
            raise ManagedInstallError("file poll_ms must be between 50 and 2000")
    if transport in ("socket", "both") and not isinstance(socket_config, dict):
        raise ManagedInstallError("socket and both transports require socket settings")
    if transport in ("socket", "both"):
        host = socket_config.get("host", "127.0.0.1")
        port = socket_config.get("port", 9000)
        token_file = socket_config.get("token_file")
        if host not in ("127.0.0.1", "::1"):
            raise ManagedInstallError("socket host must be 127.0.0.1 or ::1")
        if isinstance(port, bool) or not isinstance(port, int) or not 1 <= port <= 65535:
            raise ManagedInstallError("socket port must be between 1 and 65535")
        if not isinstance(token_file, str) or not token_file:
            raise ManagedInstallError("socket transport requires a token_file path")
        if enabled:
            from ue4ss.live.security import validate_token_file

            validate_token_file(token_to_validate or token_file)
    manifest = _read_manifest(mod)
    item = manifest["components"].get(LIVE_NAME)
    target = mod / STATE_DIR / "components" / LIVE_NAME
    if item is None:
        if not (LIVE_SOURCE / "__init__.py").is_file():
            raise ManagedInstallError(f"packaged managed live entry is missing: {LIVE_SOURCE}")
        if dry_run:
            print(f"would install and {'enable' if enabled else 'disable'} managed live component ({transport})")
            return
        _copy_package(LIVE_SOURCE, target, replace=False)
        item = {"path": f"components/{LIVE_NAME}", "enabled": False, "config": {}}
        manifest["components"][LIVE_NAME] = item
        manifest["startup_order"].append(LIVE_NAME)
    elif not target.is_dir():
        raise ManagedInstallError(f"managed live component source is missing: {target}")
    item["enabled"] = bool(enabled)
    item["config"] = {"transport": transport}
    if transport in ("file", "both"):
        item["config"]["file"] = file_config
    if transport in ("socket", "both"):
        item["config"]["socket"] = socket_config
    if dry_run:
        print(f"would {'enable' if enabled else 'disable'} managed live transport: {transport}")
        return
    _write_manifest(_manifest_path(mod), manifest)


def list_components(mod: Path) -> None:
    manifest = _read_manifest(mod)
    for name in manifest["startup_order"]:
        item = manifest["components"][name]
        print(f"{name}: {'enabled' if item['enabled'] else 'disabled'} ({item['path']})")
    if not manifest["startup_order"]:
        print("no managed components configured")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mod-dir", type=Path, default=MOD)
    parser.add_argument("--dry-run", action="store_true", help="validate and describe without changing files")
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("install", help="install the stable bootstrap and initialize an empty manifest")
    commands.add_parser("uninstall", help="restore the prior main.py or remove the bootstrap")
    enable_parser = commands.add_parser("enable", help="install/update a package and enable it at startup")
    enable_parser.add_argument("name")
    enable_parser.add_argument("--source", type=Path)
    enable_parser.add_argument("--replace", action="store_true")
    disable_parser = commands.add_parser("disable", help="disable one component without removing its source")
    disable_parser.add_argument("name")
    commands.add_parser("list", help="list configured managed components")
    live_enable = commands.add_parser("live-enable", help="enable the managed live bridge")
    live_enable.add_argument("--transport", choices=("file", "socket", "both"), default="file")
    live_enable.add_argument("--inbox")
    live_enable.add_argument("--outbox")
    live_enable.add_argument("--heartbeat")
    live_enable.add_argument("--poll-ms", type=int, default=250)
    live_enable.add_argument("--host", default="127.0.0.1")
    live_enable.add_argument("--port", type=int, default=9000)
    live_enable.add_argument("--token-file")
    commands.add_parser("live-disable", help="disable only the managed live bridge")
    args = parser.parse_args(argv)
    try:
        if args.command == "install":
            install(args.mod_dir, dry_run=args.dry_run)
        elif args.command == "uninstall":
            uninstall(args.mod_dir, dry_run=args.dry_run)
        elif args.command == "enable":
            enable(args.mod_dir, args.name, args.source, replace=args.replace, dry_run=args.dry_run)
        elif args.command == "disable":
            disable(args.mod_dir, args.name, dry_run=args.dry_run)
        elif args.command == "list":
            list_components(args.mod_dir)
        elif args.command == "live-enable":
            file_config = None
            socket_config = None
            if args.transport in ("file", "both"):
                if not all((args.inbox, args.outbox, args.heartbeat)):
                    raise ManagedInstallError("--inbox, --outbox and --heartbeat are required for file transport")
                file_config = {
                    "inbox": args.inbox,
                    "outbox": args.outbox,
                    "heartbeat": args.heartbeat,
                    "poll_ms": args.poll_ms,
                }
            if args.transport in ("socket", "both"):
                if not args.token_file:
                    raise ManagedInstallError("--token-file is required for socket transport")
                socket_config = {"host": args.host, "port": args.port, "token_file": args.token_file}
            configure_live(
                args.mod_dir,
                transport=args.transport,
                file_config=file_config,
                socket_config=socket_config,
                dry_run=args.dry_run,
            )
        elif args.command == "live-disable":
            current = _read_manifest(args.mod_dir)["components"].get(LIVE_NAME)
            if current is None:
                raise ManagedInstallError("managed live bridge is not configured")
            config = current.get("config", {})
            configure_live(
                args.mod_dir,
                transport=config.get("transport", "file"),
                file_config=config.get("file") if config.get("transport", "file") in ("file", "both") else None,
                socket_config=config.get("socket") if config.get("transport") in ("socket", "both") else None,
                enabled=False,
                dry_run=args.dry_run,
            )
        return 0
    except (ManagedInstallError, OSError, ValueError) as error:
        print(f"managed runtime: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
