#!/usr/bin/env python3
"""Writes the typings of the base `ue4ss` module that are shipped in the repository (python/typings/ue4ss and python/mock/ue4ss), so an editor completes
`ue4ss.find_first_of`, `register_hook`, `Key`, ... before any game has generated its own typings.

    python3 -I tools/gen_base_stubs.py            # rewrite python/typings/ue4ss
    python3 -I tools/gen_base_stubs.py --check    # exit 1 if the committed files differ from what would be written

The stub is built by the same code the game uses (ue4ss.basestubs), from the off-game module python/mock/ue4ss. Engine and game
classes are not in it: those come from the running game, `ue4ss.engine.generate_stubs(folder)` (docs/TYPED_API.md), and the folder
they are written to (`stubs/`, the stubPath) takes priority over these files.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "python" / "typings" / "ue4ss"
OUTS = (OUT, ROOT / "python" / "mock" / "ue4ss")
HEADER = "# Generated by tools/gen_base_stubs.py from python/mock/ue4ss. Do not edit; run the tool again."

ENGINE_STUB = HEADER + '''
# Engine and game classes are not known without a game: every name is Any here. Generate the real typings in the game with
# ue4ss.engine.generate_stubs(folder) (docs/TYPED_API.md).
from typing import Any

class EngineError(Exception): ...
def find(path: str) -> Any: ...
def package(name: str) -> Any: ...
def lookup(name: str) -> Any: ...
def from_object(obj: Any) -> Any: ...
def class_for(uclass: Any) -> Any: ...
def generate_stubs(folder: str, packages: list[str] | None = ..., blueprints: bool = ..., dependencies: bool = ..., load: list[str] | None = ..., load_limit: int = ...) -> dict[str, Any]: ...
def __getattr__(name: str) -> Any: ...
'''


def files() -> dict:
    """{path: text} of everything the tool writes."""
    sys.path.insert(0, str(ROOT / "python" / "mock"))
    try:
        import ue4ss
        from ue4ss import basestubs
    finally:
        sys.path.pop(0)
    base = basestubs.make_base_stub(ue4ss).split("\n", 1)[1]      # replace the generator's own first line
    result = {}
    for out in OUTS:
        result.update({out / "__init__.pyi": HEADER + "\n" + base, out / "engine" / "__init__.pyi": ENGINE_STUB, out / "py.typed": ""})
    return result


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="do not write; fail if the committed files are out of date")
    args = parser.parse_args(argv)
    stale = []
    for path, text in files().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    if args.check and stale:
        print("out of date: " + ", ".join(str(p.relative_to(ROOT)) for p in stale) + " (run python3 -I tools/gen_base_stubs.py)")
        return 1
    print(f"{len(stale)} file(s) written" if not args.check else "the shipped ue4ss typings are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
