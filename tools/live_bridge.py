"""Generate the resident in-game bridge for the live execution protocol."""

from __future__ import annotations


BRIDGE = r'''# generated by tools.live_bridge: resident local execution bridge
import builtins
import contextlib
import io
import json
import os
import time
import traceback

import ue4ss

INBOX = __INBOX__
OUTBOX = __OUTBOX__
HEARTBEAT = __HEARTBEAT__
POLL_MS = __POLL_MS__
MAX_CODE_BYTES = 128 * 1024
MAX_OUTPUT_CHARS = 64 * 1024
MAX_TIMEOUT_SECONDS = 600.0
_busy = False
_stopping = False
_generation = 1
_poll_failures = 0
_scope = {}
_jobs = {}
_cleanup_groups = {}
_pending_wait = None


class _RawJson:
    """Wrap an already JSON-safe value so `_safe` passes it through without depth checks."""

    def __init__(self, value):
        self.value = value


def _safe(value, depth=0):
    if isinstance(value, _RawJson):
        return value.value
    if value is None or isinstance(value, (bool, int, float, str)):
        return value if not isinstance(value, str) else value[:500]
    if depth >= 3:
        return repr(value)[:500]
    if isinstance(value, dict):
        return {str(k)[:80]: _safe(v, depth + 1) for k, v in list(value.items())[:32]}
    if isinstance(value, (list, tuple, set)):
        return [_safe(v, depth + 1) for v in list(value)[:32]]
    try:
        if hasattr(value, "to_dict"):
            return _safe(value.to_dict(), depth + 1)
        if hasattr(value, "get_fname"):
            return {"name": value.get_fname().to_string(), "class": value.get_class().get_fname().to_string()}
    except Exception:
        pass
    return repr(value)[:500]


def _write_response(request_id, status, stdout="", stderr="", result=None, error=None, duration=0.0):
    os.makedirs(OUTBOX, exist_ok=True)
    record = {"protocol": 1, "id": request_id, "status": status, "stdout": stdout[:MAX_OUTPUT_CHARS],
              "stderr": stderr[:MAX_OUTPUT_CHARS], "result": _safe(result), "error": _safe(error),
              "duration": duration, "completed": time.time()}
    temporary = os.path.join(OUTBOX, "." + request_id + ".tmp")
    target = os.path.join(OUTBOX, request_id + ".json")
    if os.path.exists(target):
        return
    with open(temporary, "w", encoding="utf-8") as handle:
        json.dump(record, handle, ensure_ascii=False, separators=(",", ":"))
        handle.write("\n")
    os.replace(temporary, target)


def _write_state(request_id, state, detail=None):
    os.makedirs(OUTBOX, exist_ok=True)
    record = {"protocol": 1, "id": request_id, "state": state, "time": time.time()}
    if detail is not None:
        record["detail"] = _safe(detail)
    temporary = os.path.join(OUTBOX, "." + request_id + ".state.tmp")
    target = os.path.join(OUTBOX, request_id + ".state.json")
    with open(temporary, "w", encoding="utf-8") as handle:
        json.dump(record, handle, ensure_ascii=False, separators=(",", ":"))
    os.replace(temporary, target)


def _recover_claims():
    try:
        names = [name for name in os.listdir(INBOX) if name.endswith(".running")]
    except OSError:
        names = []
    for name in names:
        request_id = name[:-len(".running")]
        _write_state(request_id, "unknown", "bridge restarted while request was running")
        _write_response(request_id, "unknown", error={"type": "UnknownOutcome", "message": "bridge restarted while request was running"})
        try:
            os.remove(os.path.join(INBOX, name))
        except OSError:
            pass


def _validate(record):
    if not isinstance(record, dict):
        return "request must be an object"
    if record.get("protocol") != 1:
        return "unsupported protocol version"
    if not isinstance(record.get("id"), str) or not record["id"]:
        return "request id is required"
    if record.get("operation") not in ("execute", "reset", "job_start", "job_status", "job_result", "cleanup", "reload", "status", "travel", "stop", "wait_until"):
        return "unsupported operation"
    code = record.get("code", "")
    if not isinstance(code, str):
        return "code must be a string"
    if len(code.encode("utf-8")) > MAX_CODE_BYTES:
        return "code exceeds the maximum size"
    timeout = record.get("timeout", 30.0)
    if isinstance(timeout, bool) or not isinstance(timeout, (int, float)) or not 0 < timeout <= MAX_TIMEOUT_SECONDS:
        return "invalid timeout"
    deadline = record.get("deadline")
    if isinstance(deadline, bool) or not isinstance(deadline, (int, float)):
        return "deadline is required"
    if time.time() > deadline:
        return "request deadline has expired"
    if not isinstance(record.get("args", {}), dict):
        return "args must be an object"
    if record["operation"] == "execute" and not code.strip():
        return "execute requires non-empty code"
    return None


def _job_view(job):
    return {"id": job["id"], "state": job["state"], "generation": job["generation"],
            "result": _safe(job.get("result")), "stdout": job.get("stdout", "")[:MAX_OUTPUT_CHARS],
            "stderr": job.get("stderr", "")[:MAX_OUTPUT_CHARS], "error": _safe(job.get("error")),
            "duration": job.get("duration", 0.0)}


def _register_cleanup(group, name, callback):
    if not isinstance(group, str) or not group or not isinstance(name, str) or not name or not callable(callback):
        raise TypeError("register_cleanup(group, name, callable) requires non-empty names")
    _cleanup_groups.setdefault(group, {})[name] = callback
    return {"group": group, "name": name}


def _new_scope():
    return {"__name__": "__live_session__", "ue4ss": ue4ss, "result": None,
            "register_cleanup": _register_cleanup}


def _cleanup_group(group):
    names = list(_cleanup_groups) if group in (None, "", "*") else [group]
    outcomes = []
    for group_name in names:
        resources = _cleanup_groups.pop(group_name, {})
        for name, callback in resources.items():
            try:
                callback()
                outcomes.append({"group": group_name, "name": name, "ok": True})
            except Exception as error:
                outcomes.append({"group": group_name, "name": name, "ok": False,
                                 "error": _RawJson({"type": type(error).__name__, "message": str(error)})})
    return outcomes


_scope = _new_scope()


def _start_job(job_id, code):
    job = _jobs.get(job_id)
    if job is None or job["state"] != "queued":
        return
    job["state"] = "running"
    began = time.monotonic()
    stdout, stderr = io.StringIO(), io.StringIO()
    try:
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
            exec(compile(code, "<live-job>", "exec"), _scope, _scope)
        job.update(state="completed", result=_scope.get("result"), stdout=stdout.getvalue(), stderr=stderr.getvalue())
    except Exception as error:
        job.update(state="failed", stdout=stdout.getvalue(), stderr=stderr.getvalue(),
                    error={"type": type(error).__name__, "message": str(error), "traceback": traceback.format_exc()})
    job["duration"] = time.monotonic() - began


def _start_wait(request_id, record):
    global _pending_wait
    if _pending_wait is not None:
        raise ValueError("another wait_until is already pending")
    _pending_wait = {"request_id": request_id,
                     "code": record.get("code", "").strip(),
                     "deadline": record.get("deadline"),
                     "began_mono": time.monotonic()}
    _write_state(request_id, "waiting")


def _poll_pending_wait():
    # A wait_until never blocks the poll loop: we re-evaluate the check on every
    # engine tick (game-thread safe, same scope the jobs write into) and reply
    # once truthy or the deadline passes. With no check snippet it is a pure
    # sleep - block the full timeout then reply ok.
    global _pending_wait
    wait = _pending_wait
    if wait is None or _stopping:
        return
    request_id = wait["request_id"]
    if wait["code"]:
        try:
            final = eval(compile(wait["code"], "<wait-check>", "eval"), _scope, _scope)
        except Exception as error:
            _write_response(request_id, "error",
                            error={"type": type(error).__name__, "message": "wait check raised: " + str(error),
                                   "traceback": traceback.format_exc()})
            _write_state(request_id, "failed", error)
            _pending_wait = None
            return
        if final:
            duration = time.monotonic() - wait["began_mono"]
            _write_response(request_id, "ok", result=final, duration=duration)
            _write_state(request_id, "completed")
            _pending_wait = None
            return
    duration = time.monotonic() - wait["began_mono"]
    if time.time() > wait["deadline"]:
        if wait["code"]:
            _write_response(request_id, "timeout", duration=duration,
                            error={"type": "Timeout", "message": "wait condition not met before timeout"})
            _write_state(request_id, "timeout")
        else:
            _write_response(request_id, "ok", result={"slept": True}, duration=duration)
            _write_state(request_id, "completed")
        _pending_wait = None


def _heartbeat():
    # Atomic (temporary name + rename): the client reads this file every request to
    # derive the clock offset, and a torn read would send the deadline on the wrong
    # clock.
    os.makedirs(os.path.dirname(HEARTBEAT), exist_ok=True)
    temporary = os.path.join(os.path.dirname(HEARTBEAT), ".alive.tmp")
    with open(temporary, "w", encoding="utf-8") as handle:
        handle.write(str(time.time()))
    os.replace(temporary, HEARTBEAT)


def _level_name():
    """The full name of the current world, or None when there is none (or it cannot be asked)."""
    try:
        world = ue4ss.find_first_of("World")
        return world.get_full_name() if world is not None else None
    except Exception:
        return None


def _travel(path):
    from ue4ss.engine.Engine import GameplayStatics
    world = ue4ss.find_first_of("World")
    if world is None:
        raise ue4ss.UEError("no World is available")
    GameplayStatics.OpenLevel(world, path, True, "")
    return {"map": path, "requested": True}


def _run(record):
    global _busy, _stopping, _generation, _scope, _pending_wait
    request_id = record.get("id", "invalid")
    began = time.monotonic()
    validation_error = _validate(record)
    if validation_error:
        status = "timeout" if validation_error == "request deadline has expired" else "rejected"
        error_type = "Timeout" if status == "timeout" else "ProtocolError"
        _write_response(request_id, status, error={"type": error_type, "message": validation_error})
        _write_state(request_id, status, validation_error)
        return
    if _busy:
        _write_response(request_id, "rejected", error={"type": "Busy", "message": "another request is running"})
        return
    _busy = True
    _write_state(request_id, "running")
    stdout, stderr = io.StringIO(), io.StringIO()
    try:
        operation = record.get("operation")
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
            if operation == "execute":
                exec(compile(record.get("code", ""), "<live-execute>", "exec"), _scope, _scope)
                result = _scope.get("result")
            elif operation == "reset":
                if _pending_wait is not None:
                    _write_response(_pending_wait["request_id"], "rejected",
                                    error={"type": "Reset", "message": "session reset while a wait was pending"})
                    _pending_wait = None
                reset_outcomes = _cleanup_group("*")
                _generation += 1
                _scope = _new_scope()
                _jobs.clear()
                result = {"generation": _generation, "reset": True, "cleanup": reset_outcomes}
            elif operation == "status":
                result = {"alive": True, "game_thread": True, "generation": _generation, "level": _level_name(),
                          "jobs": [_job_view(job) for job in _jobs.values()]}
            elif operation == "job_start":
                job_id = "job-" + request_id
                _jobs[job_id] = {"id": job_id, "state": "queued", "generation": _generation,
                                 "result": None, "stdout": "", "stderr": "", "error": None, "duration": 0.0}
                ue4ss.execute_with_delay(0, lambda: _start_job(job_id, record.get("code", "")))
                result = _job_view(_jobs[job_id])
            elif operation in ("job_status", "job_result"):
                job_id = record.get("args", {}).get("job_id", "")
                if job_id not in _jobs:
                    raise ValueError("unknown job: " + repr(job_id))
                result = _job_view(_jobs[job_id])
            elif operation == "cleanup":
                result = {"outcomes": _cleanup_group(record.get("args", {}).get("group"))}
            elif operation == "travel":
                result = _travel(record.get("args", {}).get("map", ""))
            elif operation == "reload":
                result = {"reloading": True}
            elif operation == "wait_until":
                _start_wait(request_id, record)
                return
            elif operation == "stop":
                result = {"stopping": True}
                _stopping = True
            else:
                raise ValueError("unsupported operation: " + repr(operation))
        duration = time.monotonic() - began
        if duration > float(record.get("timeout", 30.0)):
            _write_response(request_id, "timeout", stdout.getvalue(), stderr.getvalue(), duration=duration,
                            error={"type": "Timeout", "message": "execution exceeded its deadline"})
            _write_state(request_id, "timeout")
        else:
            _write_response(request_id, "ok", stdout.getvalue(), stderr.getvalue(), result, duration=duration)
            _write_state(request_id, "completed")
    except Exception as error:
        duration = time.monotonic() - began
        _write_response(request_id, "error", stdout.getvalue(), stderr.getvalue(), duration=duration,
                        error={"type": type(error).__name__, "message": str(error), "traceback": traceback.format_exc()})
        _write_state(request_id, "failed", error)
    finally:
        _busy = False
    if record.get("operation") == "stop":
        print("live bridge stopped")
        return
    if record.get("operation") == "reload" and not _stopping:
        ue4ss.reload()


def _poll():
    # The reschedule in the finally block is what keeps the bridge alive: a transient
    # transport error (the session folder can be on a slow or networked drive) must
    # never kill the chain silently - a dead poll starves every later request.
    global _poll_failures
    try:
        _heartbeat()
        _recover_claims()
        _poll_pending_wait()
        if not _stopping:
            try:
                os.makedirs(INBOX, exist_ok=True)
                names = sorted(name for name in os.listdir(INBOX) if name.endswith(".json"))
            except OSError:
                names = []
            if names and not _busy:
                name = names[0]
                path = os.path.join(INBOX, name)
                running = path[:-len(".json")] + ".running"
                try:
                    os.rename(path, running)
                    with open(running, encoding="utf-8") as handle:
                        record = json.load(handle)
                    os.remove(running)
                    _run(record)
                except Exception as error:
                    request_id = name[:-5]
                    _write_response(request_id, "rejected", error={"type": type(error).__name__, "message": str(error)})
                    _write_state(request_id, "failed", error)
                    try:
                        os.remove(running)
                    except OSError:
                        pass
    except Exception as error:
        _poll_failures += 1
        if _poll_failures == 1 or _poll_failures % 120 == 0:
            print("live bridge poll error (x%d): %s" % (_poll_failures, repr(error)[:200]))
    else:
        if _poll_failures:
            print("live bridge poll recovered after %d failure(s)" % _poll_failures)
        _poll_failures = 0
    finally:
        if not _stopping:
            ue4ss.execute_with_delay(POLL_MS, _poll)


print("live bridge ready")
ue4ss.execute_with_delay(0, _poll)
'''


def build_bridge(inbox: str, outbox: str, heartbeat: str, poll_ms: int = 250) -> str:
    """Return a resident `main.py` source for a live protocol session."""
    if not isinstance(poll_ms, int) or not 50 <= poll_ms <= 2000:
        raise ValueError("poll_ms must be between 50 and 2000")
    return (BRIDGE.replace("__INBOX__", repr(str(inbox)))
            .replace("__OUTBOX__", repr(str(outbox)))
            .replace("__HEARTBEAT__", repr(str(heartbeat)))
            .replace("__POLL_MS__", str(poll_ms)))
