"""Generate a thin resident bootstrap for the packaged file transport adapter."""

from __future__ import annotations


BRIDGE = r'''# generated by tools.live_bridge: resident local execution bridge
import time
import ue4ss
from ue4ss.live.file_transport import FileTransport

INBOX = __INBOX__
OUTBOX = __OUTBOX__
HEARTBEAT = __HEARTBEAT__
POLL_MS = __POLL_MS__

_transport = FileTransport(None, INBOX, OUTBOX, HEARTBEAT, POLL_MS, ue_module=ue4ss)
_core = _transport.core
_busy = False
_stopping = False
_generation = _core.scope_generation
_scope = _core.scope
_jobs = _core.jobs
_cleanup_groups = _core.cleanup_groups
_pending_wait = _core.pending_wait
_poll_failures = 0
_heartbeat = _transport._heartbeat


def _sync_compat_state():
    global _stopping, _generation, _scope, _jobs, _cleanup_groups, _pending_wait, _poll_failures
    _stopping = _core.stopping
    _generation = _core.scope_generation
    _scope = _core.scope
    _jobs = _core.jobs
    _cleanup_groups = _core.cleanup_groups
    _pending_wait = _core.pending_wait
    _poll_failures = _transport.poll_failures


def _run(record):
    _core._wall = time.time
    _core._mono = time.monotonic
    try:
        return _transport.run_record(record, busy=_busy)
    finally:
        _sync_compat_state()


def _poll():
    try:
        _core._wall = time.time
        _core._mono = time.monotonic
        _transport.poll(heartbeat=_heartbeat)
    finally:
        _sync_compat_state()


print("live bridge ready")
ue4ss.execute_with_delay(0, _poll)
'''


def build_bridge(inbox: str, outbox: str, heartbeat: str, poll_ms: int = 250) -> str:
    """Return a resident bootstrap that imports the packaged live core/adapter."""
    if not isinstance(poll_ms, int) or isinstance(poll_ms, bool) or not 50 <= poll_ms <= 2000:
        raise ValueError("poll_ms must be between 50 and 2000")
    return (
        BRIDGE.replace("__INBOX__", repr(str(inbox)))
        .replace("__OUTBOX__", repr(str(outbox)))
        .replace("__HEARTBEAT__", repr(str(heartbeat)))
        .replace("__POLL_MS__", str(poll_ms))
    )
