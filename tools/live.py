#!/usr/bin/env python3
"""Run Python in the running game from outside: a small resident script in the game executes what you send.

    python tools/live.py install          # make the bridge the mod's main.py (your main.py is kept), then start the game
    python tools/live.py status           # is the bridge alive?
    python tools/live.py exec "print(len(ue4ss.find_all_of('Actor')))"
    python tools/live.py exec -f my_snippet.py
    python tools/live.py repl             # type lines, see the output; variables stay between lines
    python tools/live.py stop             # end the bridge in the game
    python tools/live.py --endpoint tcp://127.0.0.1:9000 --token-file live.token status
    python tools/live.py scripts          # managed-script operations require managed bootstrap
    python tools/live.py uninstall        # put your main.py back

How it works: the bridge re-arms itself on the game thread every 250 ms, picks up request files from <session>/inbox, runs the
code with exec in one persistent scope, and writes the printed output, the value of a variable named `result` and any
traceback to <session>/outbox. The session folder is dist/PythonScripting/live (PYUE_LIVE_DIR overrides it). Nothing listens
on the network by default; an explicitly configured managed runtime may enable authenticated loopback TCP. tools/live_mcp.py
offers the same operations to an AI assistant as MCP tools.
"""
import argparse
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from live_bridge import build_bridge  # noqa: E402
from live_client import LiveClient, LiveClientError, client_from_environment  # noqa: E402
import managed  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
MOD = ROOT / "dist" / "PythonScripting"
BRIDGE_MARK = "# generated by tools.live_bridge"
BACKUP_NAME = "main.py.before-live"


def session_dir(path: Path = None) -> Path:
    return Path(path or os.environ.get("PYUE_LIVE_DIR", str(MOD / "live")))


def read_source_file(path: Path, limit: int = 128 * 1024) -> bytes:
    """Read at most one bounded source file, without buffering an oversized file."""
    with Path(path).open("rb") as source:
        content = source.read(limit + 1)
    if len(content) > limit:
        raise LiveClientError(f"source file exceeds the {limit} byte limit")
    return content


def game_path(path: Path) -> str:
    """The path as the game (a Windows process) sees it: /mnt/c/x -> C:\\x when this tool runs under WSL."""
    text = str(path)
    match = re.match(r"^/mnt/([a-z])/(.*)$", text)
    if os.name != "nt" and match:
        return f"{match.group(1).upper()}:\\" + match.group(2).replace("/", "\\")
    return text


def install(mod: Path = MOD, session: Path = None, poll_ms: int = 250, say=print) -> None:
    session = session_dir(session)
    scripts = mod / "python_scripts"
    if not scripts.is_dir():
        raise LiveClientError(f"{scripts} does not exist: package the mod first (tools/install.py or tools/package_mod.py)")
    main_py, backup = scripts / "main.py", scripts / BACKUP_NAME
    if main_py.exists() and not main_py.read_text(encoding="utf-8", errors="replace").startswith(BRIDGE_MARK):
        if backup.exists():
            raise LiveClientError(f"{backup} already exists and main.py is not the bridge: resolve by hand which one is your script")
        main_py.replace(backup)
        say(f"your main.py is kept as {backup.name}")
    for folder in ("inbox", "outbox"):
        (session / folder).mkdir(parents=True, exist_ok=True)
    main_py.write_text(build_bridge(game_path(session / "inbox"), game_path(session / "outbox"), game_path(session / "alive"), poll_ms), encoding="utf-8")
    say(f"the bridge is installed as {main_py}. Start the game (or reload the script in a running game), then:  python tools/live.py status")


def install_managed(
    mod: Path,
    session: Path,
    *,
    transport: str,
    poll_ms: int,
    port: int,
    token_file: str | None,
    dry_run: bool = False,
    say=print,
) -> None:
    scripts = mod / "python_scripts"
    main_py = scripts / "main.py"
    if not scripts.is_dir():
        raise LiveClientError(f"{scripts} does not exist: package the mod first")
    if not dry_run:
        managed.install(mod, say=say)
    else:
        managed.install(mod, say=say, dry_run=True)

    file_config = None
    if transport in ("file", "both"):
        if not dry_run:
            for folder in ("inbox", "outbox"):
                (session / folder).mkdir(parents=True, exist_ok=True)
        file_config = {
            "inbox": game_path(session / "inbox"),
            "outbox": game_path(session / "outbox"),
            "heartbeat": game_path(session / "alive"),
            "poll_ms": poll_ms,
        }
    socket_config = None
    if transport in ("socket", "both"):
        if not token_file:
            raise LiveClientError("managed socket transport requires --token-file; provision it with a private token-file tool")
        token_path = Path(token_file)
        if not dry_run:
            from ue4ss.live.security import validate_token_file

            validate_token_file(token_path)
        socket_config = {
            "host": "127.0.0.1",
            "port": port,
            "token_file": game_path(token_path),
        }
    managed.configure_live(
        mod,
        transport=transport,
        file_config=file_config,
        socket_config=socket_config,
        dry_run=dry_run,
        token_to_validate=token_file,
    )


def uninstall(mod: Path = MOD, say=print) -> None:
    main_py, backup = mod / "python_scripts" / "main.py", mod / "python_scripts" / BACKUP_NAME
    if main_py.exists() and not main_py.read_text(encoding="utf-8", errors="replace").startswith(BRIDGE_MARK):
        raise LiveClientError("main.py is not the bridge; nothing to remove")
    if backup.exists():
        backup.replace(main_py)
        say("your main.py is back")
    elif main_py.exists():
        main_py.unlink()
        say("the bridge is removed (there was no main.py before it)")
    say("in a running game the bridge keeps running until  python tools/live.py stop  or a reload")


def show(response: dict, out=None, err=None) -> None:
    out, err = out or sys.stdout, err or sys.stderr
    if response.get("stdout"):
        out.write(response["stdout"] if response["stdout"].endswith("\n") else response["stdout"] + "\n")
    if response.get("stderr"):
        err.write(response["stderr"] if response["stderr"].endswith("\n") else response["stderr"] + "\n")
    if response.get("result") is not None:
        out.write(f"result: {response['result']!r}\n")


def prepare(code: str) -> str:
    """An expression becomes `result = (expression)` so that its value is shown, like at a Python prompt; anything else first
    clears `result`, so that the value of an earlier request is not shown again."""
    try:
        compile(code.strip(), "<live>", "eval")
    except SyntaxError:
        return "result = None\n" + code
    return "result = (" + code.strip() + ")"


def execute(client: LiveClient, code: str, timeout: float) -> int:
    code = prepare(code)
    if not client.is_alive():
        if getattr(client, "is_socket", False):
            print(f"live: TCP bridge unavailable at {client.endpoint}; check the SSH tunnel, endpoint, and token file", file=sys.stderr)
        else:
            print("live: no bridge is running (python tools/live.py install, then start the game)", file=sys.stderr)
        return 1
    try:
        show(client.request("execute", code=code, timeout=timeout))
    except LiveClientError as error:
        print(f"live: {error}", file=sys.stderr)
        return 1
    return 0


def repl(client: LiveClient, timeout: float, read=input) -> int:
    print("Python in the game. A line ending with ':' starts a block, an empty line ends it. Ctrl+C or 'exit' leaves.")
    block = []
    while True:
        try:
            line = read("... " if block else ">>> ")
        except (EOFError, KeyboardInterrupt):
            print()
            return 0
        if not block and line.strip() in ("exit", "quit"):
            return 0
        if block:
            if line.strip():
                block.append(line)
                continue
            code, block = "\n".join(block), []
        elif line.rstrip().endswith(":"):
            block.append(line)
            continue
        else:
            code = line
        if code.strip():
            execute(client, code, timeout)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--mod-dir", type=Path, default=MOD, help="the packaged PythonScripting folder (default: %(default)s)")
    parser.add_argument("--session-dir", type=Path, help="the live session folder (default: PYUE_LIVE_DIR or <mod-dir>/live)")
    parser.add_argument("--endpoint", help="authenticated TCP endpoint (tcp://127.0.0.1:PORT or tcp://[::1]:PORT); overrides PYUE_LIVE_ENDPOINT")
    parser.add_argument("--token-file", help="restricted bearer-token file (default: PYUE_LIVE_TOKEN_FILE)")
    sub = parser.add_subparsers(dest="command", required=True)
    install_parser = sub.add_parser("install", help="make the bridge the mod's main.py")
    install_parser.add_argument("--poll-ms", type=int, default=250, help="how often the bridge looks for requests (default: %(default)s)")
    install_parser.add_argument("--managed", action="store_true", help="install/use the stable managed bootstrap and register live as a component")
    install_parser.add_argument("--transport", choices=("file", "socket", "both"), default="file",
                                help="managed transport selection (file remains the default)")
    install_parser.add_argument("--port", type=int, default=9000, help="managed loopback TCP listener port")
    install_parser.add_argument("--dry-run", action="store_true", help="describe managed changes without writing files")
    sub.add_parser("uninstall", help="put your main.py back")
    sub.add_parser("status", help="is the bridge alive?")
    exec_parser = sub.add_parser("exec", help="run code in the game")
    exec_parser.add_argument("code", nargs="?", help="the code; '-' or nothing reads standard input")
    exec_parser.add_argument("-f", "--file", type=Path, help="run this file's content")
    sub.add_parser("repl", help="an interactive prompt")
    sub.add_parser("reset", help="forget the variables of the session")
    sub.add_parser("stop", help="end the bridge in the game")
    sub.add_parser("scripts", help="list managed scripts")
    outcome_parser = sub.add_parser("outcome", help="look up a request outcome without replaying it")
    outcome_parser.add_argument("request_id")
    for action in ("start", "stop"):
        script_parser = sub.add_parser(f"script-{action}", help=f"{action} one managed script")
        script_parser.add_argument("name")
    load_parser = sub.add_parser("script-load", help="load one session-only script source file")
    load_parser.add_argument("name")
    load_parser.add_argument("-f", "--file", type=Path, required=True)
    reload_parser = sub.add_parser("script-reload", help="reload one managed script, optionally replacing its source")
    reload_parser.add_argument("name")
    reload_parser.add_argument("-f", "--file", type=Path, help="replacement single-file source; omitted to reuse the loaded source")
    parser.add_argument("--timeout", type=float, default=30.0, help="seconds to wait for the game (default: %(default)s)")
    args = parser.parse_args(argv)
    mod = args.mod_dir
    try:
        if args.command in ("install", "uninstall"):
            if args.endpoint:
                raise LiveClientError("install/uninstall are local file-bridge operations and do not accept --endpoint")
            client = LiveClient(args.session_dir or os.environ.get("PYUE_LIVE_DIR", str(mod / "live")))
        else:
            client = client_from_environment(
                args.session_dir,
                endpoint=args.endpoint,
                token_file=args.token_file,
            )
    except LiveClientError as error:
        print(f"live: {error}", file=sys.stderr)
        return 2
    try:
        if args.command == "install":
            if getattr(client, "is_socket", False):
                raise LiveClientError("install configures the local file bridge; use it without --endpoint")
            session = client.root
            main_py = mod / "python_scripts" / "main.py"
            is_managed = (
                main_py.is_file()
                and main_py.read_text(encoding="utf-8", errors="replace").startswith(managed.BOOTSTRAP_MARK)
            )
            if args.managed or is_managed:
                install_managed(
                    mod,
                    session,
                    transport=args.transport,
                    poll_ms=args.poll_ms,
                    port=args.port,
                    token_file=args.token_file or os.environ.get("PYUE_LIVE_TOKEN_FILE"),
                    dry_run=args.dry_run,
                )
            elif args.transport != "file":
                raise LiveClientError("socket transport requires --managed so it can coexist with other scripts")
            elif args.dry_run:
                print(f"would install legacy file bridge as {main_py}; use --managed for component installation")
            else:
                install(mod, session, poll_ms=args.poll_ms)
        elif args.command == "uninstall":
            if getattr(client, "is_socket", False):
                raise LiveClientError("uninstall configures the local file bridge; use it without --endpoint")
            main_py = mod / "python_scripts" / "main.py"
            if main_py.is_file() and main_py.read_text(encoding="utf-8", errors="replace").startswith(managed.BOOTSTRAP_MARK):
                manifest = managed._read_manifest(mod)
                if managed.LIVE_NAME not in manifest["components"]:
                    raise LiveClientError("managed live bridge is not configured")
                managed.disable(mod, managed.LIVE_NAME)
                print("managed live bridge disabled; the stable bootstrap and other components remain installed")
            else:
                uninstall(mod)
        elif args.command == "status":
            try:
                response = client.request("status", timeout=min(args.timeout, 10.0))
            except LiveClientError as error:
                location = client.endpoint if getattr(client, "is_socket", False) else f"heartbeat {client.heartbeat}"
                print(f"live: bridge unavailable ({location}): {error}", file=sys.stderr)
                return 1
            print("the bridge is alive")
            show(response)
            return 0
        elif args.command == "exec":
            if args.file:
                code = read_source_file(args.file).decode("utf-8", errors="strict")
            else:
                code = sys.stdin.read(128 * 1024 + 1) if args.code in (None, "-") else args.code
            if len(code.encode("utf-8")) > 128 * 1024:
                raise LiveClientError("source exceeds the 128 KiB live request limit")
            return execute(client, code, args.timeout)
        elif args.command == "repl":
            return repl(client, args.timeout)
        elif args.command == "scripts":
            show(client.request("script_list", timeout=args.timeout))
        elif args.command == "outcome":
            show(client.outcome(args.request_id, timeout=min(args.timeout, 10.0)))
        elif args.command == "script-start":
            show(client.request("script_start", args={"name": args.name}, timeout=args.timeout))
        elif args.command == "script-stop":
            show(client.request("script_stop", args={"name": args.name}, timeout=args.timeout))
        elif args.command == "script-load":
            source = read_source_file(args.file)
            show(client.request("script_load", code=source.decode("utf-8", errors="strict"),
                                args={"name": args.name}, timeout=args.timeout))
        elif args.command == "script-reload":
            source = read_source_file(args.file).decode("utf-8", errors="strict") if args.file else ""
            if len(source.encode("utf-8")) > 128 * 1024:
                raise LiveClientError("source file exceeds the 128 KiB managed-script limit")
            show(client.request("script_reload", code=source, args={"name": args.name}, timeout=args.timeout))
        else:
            show(client.request(args.command, timeout=args.timeout))
    except (LiveClientError, UnicodeError, OSError) as error:
        print(f"live: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
