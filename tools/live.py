#!/usr/bin/env python3
"""Run Python in the running game from outside: a small resident script in the game executes what you send.

    python tools/live.py install          # make the bridge the mod's main.py (your main.py is kept), then start the game
    python tools/live.py status           # is the bridge alive?
    python tools/live.py exec "print(len(ue4ss.find_all_of('Actor')))"
    python tools/live.py exec -f my_snippet.py
    python tools/live.py repl             # type lines, see the output; variables stay between lines
    python tools/live.py stop             # end the bridge in the game
    python tools/live.py uninstall        # put your main.py back

How it works: the bridge re-arms itself on the game thread every 250 ms, picks up request files from <session>/inbox, runs the
code with exec in one persistent scope, and writes the printed output, the value of a variable named `result` and any
traceback to <session>/outbox. The session folder is dist/PythonScripting/live (PYUE_LIVE_DIR overrides it). Nothing listens
on the network. tools/live_mcp.py offers the same operations to an AI assistant as MCP tools.
"""
import argparse
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from live_bridge import build_bridge  # noqa: E402
from live_client import LiveClient, LiveClientError  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
MOD = ROOT / "dist" / "PythonScripting"
BRIDGE_MARK = "# generated by tools.live_bridge"
BACKUP_NAME = "main.py.before-live"


def session_dir() -> Path:
    return Path(os.environ.get("PYUE_LIVE_DIR", str(MOD / "live")))


def game_path(path: Path) -> str:
    """The path as the game (a Windows process) sees it: /mnt/c/x -> C:\\x when this tool runs under WSL."""
    text = str(path)
    match = re.match(r"^/mnt/([a-z])/(.*)$", text)
    if os.name != "nt" and match:
        return f"{match.group(1).upper()}:\\" + match.group(2).replace("/", "\\")
    return text


def install(mod: Path = MOD, session: Path = None, poll_ms: int = 250, say=print) -> None:
    session = session or session_dir()
    scripts = mod / "python_scripts"
    if not scripts.is_dir():
        raise LiveClientError(f"{scripts} does not exist: package the mod first (tools/install.py or tools/package_mod.py)")
    main_py, backup = scripts / "main.py", scripts / BACKUP_NAME
    if main_py.exists() and not main_py.read_text(encoding="utf-8", errors="replace").startswith(BRIDGE_MARK):
        if backup.exists():
            raise LiveClientError(f"{backup} already exists and main.py is not the bridge: resolve by hand which one is your script")
        main_py.replace(backup)
        say(f"your main.py is kept as {backup.name}")
    for folder in ("inbox", "outbox"):
        (session / folder).mkdir(parents=True, exist_ok=True)
    main_py.write_text(build_bridge(game_path(session / "inbox"), game_path(session / "outbox"), game_path(session / "alive"), poll_ms), encoding="utf-8")
    say(f"the bridge is installed as {main_py}. Start the game (or reload the script in a running game), then:  python tools/live.py status")


def uninstall(mod: Path = MOD, say=print) -> None:
    main_py, backup = mod / "python_scripts" / "main.py", mod / "python_scripts" / BACKUP_NAME
    if main_py.exists() and not main_py.read_text(encoding="utf-8", errors="replace").startswith(BRIDGE_MARK):
        raise LiveClientError("main.py is not the bridge; nothing to remove")
    if backup.exists():
        backup.replace(main_py)
        say("your main.py is back")
    elif main_py.exists():
        main_py.unlink()
        say("the bridge is removed (there was no main.py before it)")
    say("in a running game the bridge keeps running until  python tools/live.py stop  or a reload")


def show(response: dict, out=None, err=None) -> None:
    out, err = out or sys.stdout, err or sys.stderr
    if response.get("stdout"):
        out.write(response["stdout"] if response["stdout"].endswith("\n") else response["stdout"] + "\n")
    if response.get("stderr"):
        err.write(response["stderr"] if response["stderr"].endswith("\n") else response["stderr"] + "\n")
    if response.get("result") is not None:
        out.write(f"result: {response['result']!r}\n")


def prepare(code: str) -> str:
    """An expression becomes `result = (expression)` so that its value is shown, like at a Python prompt; anything else first
    clears `result`, so that the value of an earlier request is not shown again."""
    try:
        compile(code.strip(), "<live>", "eval")
    except SyntaxError:
        return "result = None\n" + code
    return "result = (" + code.strip() + ")"


def execute(client: LiveClient, code: str, timeout: float) -> int:
    code = prepare(code)
    if not client.is_alive():
        print("live: no bridge is running (python tools/live.py install, then start the game)", file=sys.stderr)
        return 1
    try:
        show(client.request("execute", code=code, timeout=timeout))
    except LiveClientError as error:
        print(f"live: {error}", file=sys.stderr)
        return 1
    return 0


def repl(client: LiveClient, timeout: float, read=input) -> int:
    print("Python in the game. A line ending with ':' starts a block, an empty line ends it. Ctrl+C or 'exit' leaves.")
    block = []
    while True:
        try:
            line = read("... " if block else ">>> ")
        except (EOFError, KeyboardInterrupt):
            print()
            return 0
        if not block and line.strip() in ("exit", "quit"):
            return 0
        if block:
            if line.strip():
                block.append(line)
                continue
            code, block = "\n".join(block), []
        elif line.rstrip().endswith(":"):
            block.append(line)
            continue
        else:
            code = line
        if code.strip():
            execute(client, code, timeout)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    install_parser = sub.add_parser("install", help="make the bridge the mod's main.py")
    install_parser.add_argument("--poll-ms", type=int, default=250, help="how often the bridge looks for requests (default: %(default)s)")
    sub.add_parser("uninstall", help="put your main.py back")
    sub.add_parser("status", help="is the bridge alive?")
    exec_parser = sub.add_parser("exec", help="run code in the game")
    exec_parser.add_argument("code", nargs="?", help="the code; '-' or nothing reads standard input")
    exec_parser.add_argument("-f", "--file", type=Path, help="run this file's content")
    sub.add_parser("repl", help="an interactive prompt")
    sub.add_parser("reset", help="forget the variables of the session")
    sub.add_parser("stop", help="end the bridge in the game")
    parser.add_argument("--timeout", type=float, default=30.0, help="seconds to wait for the game (default: %(default)s)")
    args = parser.parse_args(argv)
    client = LiveClient(session_dir())
    try:
        if args.command == "install":
            install(poll_ms=args.poll_ms)
        elif args.command == "uninstall":
            uninstall()
        elif args.command == "status":
            alive = client.is_alive()
            print("the bridge is alive" if alive else f"no bridge is running (no fresh heartbeat in {client.heartbeat})")
            if alive:
                show(client.request("status", timeout=min(args.timeout, 10.0)))
            return 0 if alive else 1
        elif args.command == "exec":
            code = args.file.read_text(encoding="utf-8") if args.file else (sys.stdin.read() if args.code in (None, "-") else args.code)
            return execute(client, code, args.timeout)
        elif args.command == "repl":
            return repl(client, args.timeout)
        else:
            show(client.request(args.command, timeout=args.timeout))
    except LiveClientError as error:
        print(f"live: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
